/**
 * Les pixels du plan de travail restent proches d'une taille d'écran : on ne
 * travaille pas à la résolution d'impression, la conversion en 300 dpi est
 * faite au moment de l'export (voir lib/editor/export.ts).
 */
function doc(
  width: number,
  height: number,
  background: string | PageBackground,
  layers: Layer[],
): EditorDocument {
  return {
    version: DOCUMENT_VERSION,
    canvas: { width, height },
    pages: [
      {
        ...createPage(background),
        layers: layers.map((layer) => ({
          ...layer,
          id: layer.id || createId(layer.type),
        })),
      },
    ],
  };
}

/** Fond à motif, pour les collections fleurs, monogramme, doré… */
function patternBackground(
  pattern: BackgroundPatternId,
  color: string,
  surface: string,
  size = 128,
): PageBackground {
  return { kind: "pattern", pattern, color, surface, size };
}

function gradientBackground(from: string, to: string, angle = 160): PageBackground {
  return { kind: "gradient", from, to, angle };
}

